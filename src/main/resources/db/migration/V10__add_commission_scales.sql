-- A scale is either a sales tier (minimum_sales) or a restaurant's own scale (restaurant_id).
CREATE TABLE commission_scales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT UNIQUE REFERENCES restaurants(id) ON DELETE CASCADE,
    minimum_sales NUMERIC(12, 2) UNIQUE CHECK (minimum_sales >= 0),
    service_fee NUMERIC(6, 2) NOT NULL CHECK (service_fee BETWEEN 0 AND 1000),
    CHECK ((restaurant_id IS NULL) <> (minimum_sales IS NULL))
);

CREATE TABLE commission_brackets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scale_id BIGINT NOT NULL REFERENCES commission_scales(id) ON DELETE CASCADE,
    lower_limit NUMERIC(10, 2) NOT NULL CHECK (lower_limit >= 0),
    rate_percent NUMERIC(5, 2) NOT NULL CHECK (rate_percent BETWEEN 0 AND 100),
    UNIQUE (scale_id, lower_limit)
);

-- The default scale from ADR-009.
WITH default_tier AS (
    INSERT INTO commission_scales (minimum_sales, service_fee) VALUES (0.00, 5.00)
    RETURNING id
)
INSERT INTO commission_brackets (scale_id, lower_limit, rate_percent)
SELECT default_tier.id, bracket.lower_limit, bracket.rate_percent
FROM default_tier,
     (VALUES (0.00, 6.00), (100.00, 5.00), (500.00, 4.00), (1000.00, 3.00)) AS bracket(lower_limit, rate_percent);

ALTER TABLE orders
    ADD COLUMN commission NUMERIC(10, 2) CHECK (commission >= 0),
    ADD COLUMN service_fee NUMERIC(10, 2) CHECK (service_fee >= 0);

-- Orders delivered before commission scales existed pay the default scale. The value
-- excluding VAT stays unrounded, and round on a positive numeric is half up.
UPDATE orders
SET service_fee = 5.00,
    commission = round(
          0.06 * least(total / 1.25, 100)
        + 0.05 * greatest(least(total / 1.25, 500) - 100, 0)
        + 0.04 * greatest(least(total / 1.25, 1000) - 500, 0)
        + 0.03 * greatest(total / 1.25 - 1000, 0), 2)
WHERE status = 'DELIVERED';

ALTER TABLE orders ADD CONSTRAINT orders_amounts_only_when_delivered CHECK (
    (status = 'DELIVERED') = (commission IS NOT NULL)
    AND (status = 'DELIVERED') = (service_fee IS NOT NULL)
);
