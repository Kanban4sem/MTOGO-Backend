-- Profile addresses have no street; delivery addresses always have one.
ALTER TABLE addresses ADD COLUMN street VARCHAR(100);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users(id),
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id),
    delivery_address_id BIGINT NOT NULL UNIQUE REFERENCES addresses(id),
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('WEBSITE', 'APP', 'TELEPHONE')),
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PLACED', 'ACCEPTED', 'REJECTED', 'READY', 'PICKED_UP', 'DELIVERED'))
);

CREATE INDEX idx_orders_customer_id ON orders(customer_id);
CREATE INDEX idx_orders_restaurant_id ON orders(restaurant_id);

-- An ordered menu item cannot be deleted. It is taken off the menu by making it unavailable.
CREATE TABLE order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    UNIQUE (order_id, menu_item_id)
);

CREATE INDEX idx_order_lines_menu_item_id ON order_lines(menu_item_id);

CREATE TABLE order_status_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PLACED', 'ACCEPTED', 'REJECTED', 'READY', 'PICKED_UP', 'DELIVERED')),
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_order_status_changes_order_id ON order_status_changes(order_id);
